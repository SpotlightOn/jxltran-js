/**
 * TypeScript wrapper around the WebAssembly build of jxltran, the lossless JPEG XL
 * transformation tool from the libjxl ecosystem.
 *
 * The module offers the same operations as the `jxltran` command line - orientation, crop,
 * container remux, metadata and header edits - applied in memory instead of through files:
 *
 *   jxltran --set-orientation=90 in.jxl out.jxl
 *
 * becomes
 *
 *   const transformer = await createJxlTran();
 *   const { data, undo } = transformer.setOrientation(bytes, 90);
 *
 * The options map to the command line flags of the same meaning, and `extraArgs` passes every
 * other upstream flag through verbatim, so the flag surface never falls behind the tool.
 * Everything else - validation, defaults, error messages - happens inside the tool itself.
 * Runs are synchronous: the WebAssembly module executes on the current thread.
 *
 * This file is written in "native" TypeScript: Node runs it directly by stripping the types, so the
 * tests and the CLI need no build step. Only erasable syntax is used (no enums, no namespaces, no
 * parameter properties), which `erasableSyntaxOnly` in tsconfig.json enforces. The published
 * `index.js` and `index.d.ts` are emitted into `dist/` by `tsc -p tsconfig.build.json`.
 */

// The Emscripten module is generated by build.sh and ships without type declarations.
// @ts-ignore - no declarations for the generated module
import createJxlTranWasm from "../dist/jxltran.mjs";

/** The part of the Emscripten module that this wrapper uses. */
export interface JxlTranModule {
  readonly HEAPU8: Uint8Array;
  readonly HEAPU32: Uint32Array;
  UTF8ToString(pointer: number): string;
  stringToUTF8(text: string, pointer: number, maxBytesToWrite: number): void;
  lengthBytesUTF8(text: string): number;
  _malloc(size: number): number;
  _free(pointer: number): void;
  _mv_free(pointer: number): void;
  _mv_version(): number;
  _mv_last_message(): number;
  _mv_jxltran_run(
    argv: number,
    input: number,
    inputSize: number,
    outputSlot: number,
    sizeSlot: number,
    undoSlot: number,
  ): number;
  readonly FS: JxlTranFileSystem;
}

/**
 * The virtual filesystem of the module. Flags that name a file (`--set-exif FILE`, `--extract-*`,
 * `--append-jxl`, `--set-splines-from`) read and write here, never on the host: stage input files
 * before a run and read extracted files back afterwards. Use absolute paths; directories must
 * exist (see {@link JxlTranFileSystem.mkdirTree}).
 */
export interface JxlTranFileSystem {
  /** Creates every missing directory of the given path. */
  mkdirTree(path: string): void;
  /** Writes a file into the virtual filesystem. */
  writeFile(path: string, data: Uint8Array | string): void;
  /** Reads a file written by a run, e.g. the target of an `--extract-*` flag. */
  readFile(path: string): Uint8Array;
}

/** Values of `--set-orientation`: the Exif orientation tag of the image header. */
export const ORIENTATION = {
  /** 1 - no transform. */
  normal: 1,
  /** 2 - flip horizontally. */
  flipHorizontal: 2,
  /** 3 - rotate 180 degrees (alias: 180). */
  rotate180: 3,
  /** 4 - flip vertically. */
  flipVertical: 4,
  /** 5 - transpose (rotate 90 CW + flip H). */
  transpose: 5,
  /** 6 - rotate 90 degrees clockwise (alias: 90). */
  rotate90: 6,
  /** 7 - flip H + rotate 90 CW. */
  transverse: 7,
  /** 8 - rotate 90 degrees counter-clockwise (alias: 270). */
  rotate270: 8,
} as const;

/** A value from {@link ORIENTATION}. */
export type Orientation = (typeof ORIENTATION)[keyof typeof ORIENTATION];

/** Values of `--container`: how the output file is wrapped. */
export const CONTAINER = {
  /** Preserve the input format (container or bare codestream). */
  keep: "keep",
  /** Output only the bare codestream; drops the container and all metadata boxes. */
  no: "no",
  /** Always wrap the output in a container. */
  yes: "yes",
  /** Use a container only when metadata boxes are present. */
  ifNeeded: "if-needed",
} as const;

/** A value from {@link CONTAINER}. */
export type Container = (typeof CONTAINER)[keyof typeof CONTAINER];

/** Values of `--jxlp`: how jxlp boxes are handled when the output is a container. */
export const JXLP = {
  /** Keep jxlp boxes unchanged. */
  keep: "keep",
  /** Reorder jxlp boxes by counter. */
  sort: "sort",
  /** Sort and merge all jxlp boxes into a single jxlc box. */
  merge: "merge",
} as const;

/** A value from {@link JXLP}. */
export type JxlpMode = (typeof JXLP)[keyof typeof JXLP];

/** Values of `--strip`: metadata boxes to remove from the output container. */
export const STRIP = {
  /** Exif boxes (and brob wrappers around them). */
  exif: "exif",
  /** XMP boxes (xml  type). */
  xmp: "xmp",
  /** JUMBF boxes. */
  jumbf: "jumbf",
  /** JPEG bitstream reconstruction data. */
  jbrd: "jbrd",
  /** All non-structural metadata. */
  all: "all",
} as const;

/** A value from {@link STRIP}. */
export type StripTarget = (typeof STRIP)[keyof typeof STRIP];

/** A crop region as an object; `x` and `y` default to 0. */
export interface CropRect {
  width: number;
  height: number;
  x?: number;
  y?: number;
}

/**
 * A crop region, either as an object or as a string in jxltran's `--crop` syntax (`WxH` or
 * `WxH+X+Y`, e.g. `200x150+100+50`). The string form keeps the whole syntax available.
 */
export type CropSpec = string | CropRect;

/** Options of the transforming entry points; each one maps to the flag of the same meaning. */
export interface TransformOptions {
  /** `--set-orientation=1..8|90|180|270`: set the orientation tag (Exif semantics). */
  orientation?: Orientation | number | null;
  /** `--crop=WxH+X+Y`: reversible metadata-only canvas resize. */
  crop?: CropSpec | null;
  /** `--container=keep|no|yes|if-needed`. Defaults to `CONTAINER.keep`. */
  container?: Container | null;
  /** `--jxlp=keep|sort|merge`. Defaults to `JXLP.keep`. */
  jxlp?: JxlpMode | null;
  /** `--strip=exif|xmp|...`: one target or a list; multiple targets are comma-joined. */
  strip?: StripTarget | readonly StripTarget[] | null;
  /** `--frames=N[,N...]`: restrict the frame level flags of this run to these frames. */
  frames?: readonly number[] | number | null;
  /** Appended after the typed flags: every upstream option that has no typed key. */
  extraArgs?: readonly string[];
}

/** The bytes a run produced, plus the command line that inverts it (when there is one). */
export interface TransformResult {
  /** The OUTPUT file of the run, as bytes. */
  data: Uint8Array;
  /**
   * The raw `reversible_undo` command line of the run, or `null` when the change has no inverse.
   * Program name and output file are placeholders (`jxltran-js`, `OUTPUT.jxl`) because the run
   * happened in memory; substitute them with the tool you want to execute the undo with.
   */
  undo: string | null;
}

/** One `frame_region` line of `--info`: a frame's rectangle in oriented display space. */
export interface FrameRegion {
  /** 0-based codestream frame index. */
  index: number;
  width: number;
  height: number;
  x: number;
  y: number;
}

/** The values that {@link JxlTranTransformer.info} reads from the `--info` output. */
export interface ImageInfo {
  /** Oriented display width in pixels. */
  width: number;
  /** Oriented display height in pixels. */
  height: number;
  /** The Exif orientation tag, 1..8 (`ORIENTATION`). */
  orientation: number;
  /** True when the codestream is animated. */
  animation: boolean;
  /** True when the image has an alpha channel. */
  alpha: boolean;
  /** One entry per frame, in codestream order. */
  frames: FrameRegion[];
  /** The complete `--info` text, byte for byte as the tool prints it. */
  text: string;
}

/** Thrown whenever a run of the tool fails, or its output cannot be parsed. */
export class TransformError extends Error {
  /** The exit code the tool returned (the tool itself only uses 0 and 1). */
  readonly status: number;
  /** Everything the run wrote to stderr; for a parse failure, the text that made no sense. */
  readonly stderr: string;

  constructor(message: string, status: number, stderr: string) {
    super(message);
    this.name = "TransformError";
    this.status = status;
    this.stderr = stderr;
  }
}

/** What one call into the module produced; the return type of {@link JxlTranTransformer.run}. */
export interface RunResult {
  /** The exit code the tool returned (the tool itself only uses 0 and 1). */
  status: number;
  /** The OUTPUT bytes, or `null` for read-only runs and failures. */
  data: Uint8Array | null;
  /** The raw `reversible_undo` command line, or `null` when the run has no inverse. */
  undo: string | null;
  /** Everything the run printed to stdout, byte for byte (trailing newline when non-empty). */
  stdout: string;
  /** Everything the run printed to stderr, byte for byte (trailing newline when non-empty). */
  stderr: string;
}

/** argv[0] of in-memory runs: it shows up in messages and in the undo command line. */
const PROGRAM_NAME = "jxltran-js";
/** Positional INPUT of in-memory runs; the bytes travel through the heap instead. */
const INPUT_NAME = "INPUT.jxl";
/** Positional OUTPUT of in-memory runs; nothing is written to the virtual filesystem. */
const OUTPUT_NAME = "OUTPUT.jxl";

/** Accepts a Uint8Array or an ArrayBuffer and always returns a Uint8Array view. */
function asUint8Array(input: Uint8Array | ArrayBuffer): Uint8Array {
  if (input instanceof Uint8Array) {
    return input;
  }
  if (input instanceof ArrayBuffer) {
    return new Uint8Array(input);
  }
  throw new TypeError("input must be a Uint8Array or ArrayBuffer");
}

/** Joins captured output lines the way a terminal would show them. */
function joined(lines: readonly string[]): string {
  return lines.length === 0 ? "" : `${lines.join("\n")}\n`;
}

/** Formats a crop offset the way jxltran does: -10 stays "-10", 10 becomes "+10". */
function cropOffset(value: number): string {
  return value < 0 ? `${value}` : `+${value}`;
}

/** Turns a crop region into jxltran's `--crop` syntax. */
function cropSpecOf(crop: CropSpec): string {
  if (typeof crop === "string") {
    return crop;
  }
  if (typeof crop !== "object") {
    throw new TypeError("crop must be a string (jxltran syntax) or an object");
  }
  if (!Number.isInteger(crop.width) || !Number.isInteger(crop.height)) {
    throw new TypeError("crop requires integer width and height");
  }
  const x = crop.x ?? 0;
  const y = crop.y ?? 0;
  if (!Number.isInteger(x) || !Number.isInteger(y)) {
    throw new TypeError("crop x and y must be integers when given");
  }
  return `${crop.width}x${crop.height}${cropOffset(x)}${cropOffset(y)}`;
}

/** Validates a frame selection and returns it in `--frames` syntax. */
function frameList(frames: readonly number[] | number): string {
  const list = typeof frames === "number" ? [frames] : frames;
  for (const frame of list) {
    if (!Number.isInteger(frame) || frame < 0) {
      throw new TypeError(`frames must be non-negative integers, got ${frame}`);
    }
  }
  return list.join(",");
}

/**
 * Maps the typed options to their command line flags, in a stable order, and appends
 * `extraArgs` verbatim. One mapping, used by every transforming entry point.
 */
function toArgv(options: TransformOptions): string[] {
  const argv: string[] = [];
  if (options.orientation != null) {
    argv.push(`--set-orientation=${options.orientation}`);
  }
  if (options.crop != null) {
    argv.push(`--crop=${cropSpecOf(options.crop)}`);
  }
  if (options.container != null) {
    argv.push(`--container=${options.container}`);
  }
  if (options.jxlp != null) {
    argv.push(`--jxlp=${options.jxlp}`);
  }
  if (options.strip != null) {
    const targets = typeof options.strip === "string" ? options.strip : options.strip.join(",");
    argv.push(`--strip=${targets}`);
  }
  if (options.frames != null) {
    argv.push(`--frames=${frameList(options.frames)}`);
  }
  if (options.extraArgs !== undefined) {
    argv.push(...options.extraArgs);
  }
  return argv;
}

/** Parses the `--info` text into the structured {@link ImageInfo}. */
function parseInfo(text: string): ImageInfo {
  const dimensions = /^dimensions:\s*(\d+)\s*x\s*(\d+)\s*$/m.exec(text);
  if (dimensions === null) {
    throw new TransformError('could not parse the --info output: no "dimensions" line', 1, text);
  }
  const orientation = /^exif_orientation:\s*(\d+)\s*$/m.exec(text);
  const animation = /^animation:\s*(\w+)\s*$/m.exec(text);
  const alpha = /^has_alpha_channel:\s*(\w+)\s*$/m.exec(text);

  const frames: FrameRegion[] = [];
  const frameRegion = /^frame_region:\s*(\d+)\s+(\d+)x(\d+)([+-]?\d+)([+-]?\d+)\s*$/gm;
  for (const match of text.matchAll(frameRegion)) {
    frames.push({
      index: Number(match[1]),
      width: Number(match[2]),
      height: Number(match[3]),
      x: Number(match[4]),
      y: Number(match[5]),
    });
  }

  return {
    width: Number(dimensions[1]),
    height: Number(dimensions[2]),
    orientation: orientation === null ? ORIENTATION.normal : Number(orientation[1]),
    animation: animation !== null && animation[1] === "yes",
    alpha: alpha !== null && alpha[1] === "yes",
    frames,
    text,
  };
}

/** Wraps the Emscripten module in a small, synchronous API. */
class JxlTranTransformer {
  readonly #module: JxlTranModule;
  readonly #stdout: string[];
  readonly #stderr: string[];

  constructor(module: JxlTranModule, stdout: string[], stderr: string[]) {
    this.#module = module;
    this.#stdout = stdout;
    this.#stderr = stderr;
  }

  /**
   * The virtual filesystem of the module: flags that name a file (`--set-exif FILE`,
   * `--extract-*`, `--append-jxl`, `--set-splines-from`) resolve here, not on the host.
   */
  get fs(): JxlTranFileSystem {
    return this.#module.FS;
  }

  /** The version of the embedded jxltran sources, e.g. `jxltran ec2f8c2`. */
  version(): string {
    return this.#module.UTF8ToString(this.#module._mv_version());
  }

  /**
   * Runs one complete command line in memory: the raw layer beneath every other method, and the
   * one the CLI uses to forward flags verbatim. `args` holds everything after the program name,
   * including the INPUT and OUTPUT positionals (`INPUT.jxl` and `OUTPUT.jxl` for in-memory runs,
   * as {@link JxlTranTransformer.transform} passes them); the input bytes travel separately.
   *
   * Read-only runs (`--info`, `--help`, `--extract-*`, `--info-structure`) report their text in
   * `stdout` and return `data: null` - files that `--extract-*` names are written into
   * {@link JxlTranTransformer.fs} and can be read back from there.
   */
  run(args: readonly string[], input: Uint8Array | ArrayBuffer): RunResult {
    return this.#run([PROGRAM_NAME, ...args], asUint8Array(input));
  }

  /**
   * Runs one command line in memory: program name, the INPUT and (for transforms) the OUTPUT
   * positional as placeholders, then the flags. The bytes travel in and out through the heap;
   * nothing is read from or written to the virtual filesystem. Everything the tool prints is
   * captured per call.
   */
  #run(argv: string[], input: Uint8Array): RunResult {
    const module = this.#module;

    const argumentPointers = argv.map((text) => {
      const size = module.lengthBytesUTF8(text) + 1;
      const pointer = module._malloc(size);
      module.stringToUTF8(text, pointer, size);
      return pointer;
    });
    const argvPointer = module._malloc((argv.length + 1) * 4);
    for (let index = 0; index < argv.length; index++) {
      module.HEAPU32[(argvPointer >>> 2) + index] = argumentPointers[index];
    }
    module.HEAPU32[(argvPointer >>> 2) + argv.length] = 0;

    const inputPointer = module._malloc(Math.max(input.length, 1));
    module.HEAPU8.set(input, inputPointer);
    const outputSlot = module._malloc(4);
    const sizeSlot = module._malloc(4);
    const undoSlot = module._malloc(4);
    module.HEAPU32[outputSlot >>> 2] = 0;
    module.HEAPU32[sizeSlot >>> 2] = 0;
    module.HEAPU32[undoSlot >>> 2] = 0;

    this.#stdout.length = 0;
    this.#stderr.length = 0;

    try {
      const status = module._mv_jxltran_run(argvPointer, inputPointer, input.length, outputSlot, sizeSlot, undoSlot);

      // The heap may have grown during the call: read the views from the module again.
      const outputPointer = module.HEAPU32[outputSlot >>> 2];
      const outputSize = module.HEAPU32[sizeSlot >>> 2];
      const undoPointer = module.HEAPU32[undoSlot >>> 2];
      const data = outputPointer === 0 ? null : module.HEAPU8.slice(outputPointer, outputPointer + outputSize);
      const undo = undoPointer === 0 ? null : module.UTF8ToString(undoPointer);
      if (outputPointer !== 0) {
        module._mv_free(outputPointer);
      }
      if (undoPointer !== 0) {
        module._mv_free(undoPointer);
      }

      return { status, data, undo, stdout: joined(this.#stdout), stderr: joined(this.#stderr) };
    } finally {
      module._free(undoSlot);
      module._free(sizeSlot);
      module._free(outputSlot);
      module._free(inputPointer);
      module._free(argvPointer);
      for (const pointer of argumentPointers) {
        module._free(pointer);
      }
    }
  }

  /** Throws the outcome as a TransformError: the first stderr line is the message. */
  #fail(outcome: RunResult): never {
    const firstLine = outcome.stderr
      .split("\n")
      .find((line) => line.trim() !== "")
      ?.trim();
    const wrapperMessage = this.#module.UTF8ToString(this.#module._mv_last_message());
    const message = firstLine ?? wrapperMessage ?? "";
    throw new TransformError(message === "" ? `jxltran failed with status ${outcome.status}` : message, outcome.status, outcome.stderr);
  }

  /** Reads the image header information that `--info` prints. */
  info(input: Uint8Array | ArrayBuffer): ImageInfo {
    const outcome = this.#run([PROGRAM_NAME, "--info", INPUT_NAME], asUint8Array(input));
    if (outcome.status !== 0) {
      this.#fail(outcome);
    }
    return parseInfo(outcome.stdout);
  }

  /**
   * Applies the given options to the input and returns the transformed bytes. Every option is a
   * command line flag; `extraArgs` passes the rest of the tool's flag surface through unchanged.
   *
   * @throws {TransformError} when the tool rejects the input or the options
   */
  transform(input: Uint8Array | ArrayBuffer, options: TransformOptions = {}): TransformResult {
    const argv = [PROGRAM_NAME, INPUT_NAME, OUTPUT_NAME, ...toArgv(options)];
    const outcome = this.#run(argv, asUint8Array(input));
    if (outcome.status !== 0) {
      this.#fail(outcome);
    }
    if (outcome.data === null) {
      throw new TransformError(
        "the run produced no output; read-only flags such as --info belong to info()",
        outcome.status,
        outcome.stderr,
      );
    }
    return { data: outcome.data, undo: outcome.undo };
  }

  /** Sets the orientation tag, like `--set-orientation=1..8|90|180|270`. */
  setOrientation(input: Uint8Array | ArrayBuffer, orientation: Orientation | number): TransformResult {
    return this.transform(input, { orientation });
  }

  /**
   * Crops losslessly, like `--crop=WxH+X+Y`: a reversible metadata-only resize of the canvas.
   * Coordinates are in display space (as decoders show the image after the orientation tag), and
   * any signed combination is allowed - negative offsets add padding instead of cutting.
   */
  crop(input: Uint8Array | ArrayBuffer, rect: CropSpec, options: TransformOptions = {}): TransformResult {
    return this.transform(input, { ...options, crop: rect });
  }

  /** Strips metadata boxes from the output, like `--strip=exif|xmp|jumbf|jbrd|all`. */
  strip(
    input: Uint8Array | ArrayBuffer,
    targets: StripTarget | readonly StripTarget[],
    options: TransformOptions = {},
  ): TransformResult {
    return this.transform(input, { ...options, strip: targets });
  }

  /** Chooses the output wrapping, like `--container=keep|no|yes|if-needed`. */
  container(
    input: Uint8Array | ArrayBuffer,
    mode: Container,
    options: TransformOptions = {},
  ): TransformResult {
    return this.transform(input, { ...options, container: mode });
  }

  /** Chooses how jxlp boxes are written, like `--jxlp=keep|sort|merge`. */
  jxlp(input: Uint8Array | ArrayBuffer, mode: JxlpMode, options: TransformOptions = {}): TransformResult {
    return this.transform(input, { ...options, jxlp: mode });
  }
}

/**
 * Loads the WebAssembly module and returns the transformer. One module instance per call; create
 * it once and reuse it - runs are synchronous and share nothing between instances.
 */
export async function createJxlTran(): Promise<JxlTranTransformer> {
  const stdout: string[] = [];
  const stderr: string[] = [];
  const module = (await createJxlTranWasm({
    print: (line: string) => stdout.push(line),
    printErr: (line: string) => stderr.push(line),
  })) as JxlTranModule;
  return new JxlTranTransformer(module, stdout, stderr);
}

export type { JxlTranTransformer };
